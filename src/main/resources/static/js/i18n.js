let currentLang = localStorage.getItem('lang') || 'en';

function toggleLanguage(e) {
    if(e) e.preventDefault();
    currentLang = currentLang === 'en' ? 'ta' : 'en';
    localStorage.setItem('lang', currentLang);
    applyTranslations();
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translatedText = translations[currentLang]?.[key];
        if (translatedText) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translatedText;
            } else {
                let textNode = Array.from(element.childNodes).find(node => node.nodeType === Node.TEXT_NODE);
                if (textNode) {
                    textNode.nodeValue = " " + translatedText;
                } else {
                    element.innerText = translatedText;
                }
            }
        }
    });
}

// Page Loader Injector & Smooth Page Transition Handler
function initPageLoader() {
    let loader = document.getElementById('pageLoader');
    if (!loader) {
        loader = document.createElement('div');
        loader.id = 'pageLoader';
        loader.className = 'page-loader';
        loader.innerHTML = `
            <div class="loader-logo-wrap">
                <div class="loader-ring"></div>
                <div class="brand-logo-icon" style="width: 56px; height: 56px;">
                    <svg viewBox="0 0 100 100" fill="none" xmlns="http://www.w3.org/2000/svg">
                        <defs>
                            <linearGradient id="loaderLogoGrad" x1="0" y1="0" x2="100" y2="100">
                                <stop offset="0%" stop-color="#38bdf8"/>
                                <stop offset="100%" stop-color="#0284c7"/>
                            </linearGradient>
                        </defs>
                        <rect x="47" y="12" width="6" height="76" rx="3" fill="url(#loaderLogoGrad)" />
                        <circle cx="50" cy="14" r="7" fill="#38bdf8" />
                        <path d="M 28 28 C 72 24, 72 46, 50 50 C 28 54, 28 76, 72 72" stroke="url(#loaderLogoGrad)" stroke-width="8.5" stroke-linecap="round" fill="none"/>
                    </svg>
                </div>
            </div>
        `;
        document.body.prepend(loader);
    }

    // Hide loader once DOM & resources are ready
    setTimeout(() => {
        loader.classList.add('hidden');
    }, 250);

    // Attach smooth loading transition to internal page links
    document.querySelectorAll('a[href]').forEach(link => {
        const href = link.getAttribute('href');
        if (href && !href.startsWith('#') && !href.startsWith('javascript') && !href.startsWith('http')) {
            link.addEventListener('click', function(e) {
                if (e.ctrlKey || e.metaKey || e.shiftKey || link.target === '_blank') return;
                e.preventDefault();
                loader.classList.remove('hidden');
                setTimeout(() => {
                    window.location.href = href;
                }, 200);
            });
        }
    });
}

document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();
    initPageLoader();
});
